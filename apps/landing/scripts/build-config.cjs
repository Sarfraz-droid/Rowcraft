'use strict';
const { existsSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const root = resolve(__dirname, '..');
if (existsSync(resolve(root, '.env'))) process.loadEnvFile(resolve(root, '.env'));
// Explicit allowlist: personal API keys and unrelated environment values must never reach the browser.
const token = process.env.POSTHOG_PROJECT_TOKEN || '';
const host = process.env.POSTHOG_HOST || '';
if (token && !/^phc_[a-zA-Z0-9]+$/.test(token)) throw new Error('Expected a public PostHog project token (phc_), never a personal API key.');
if (host && new URL(host).protocol !== 'https:') throw new Error('POSTHOG_HOST must use HTTPS.');
if (!token || !host) console.warn('PostHog is disabled: configure POSTHOG_PROJECT_TOKEN and POSTHOG_HOST.');
writeFileSync(resolve(root, 'runtime-config.js'), `// Generated by npm run build. Public browser configuration only.\nwindow.ROWCRAFT_POSTHOG_PROJECT_TOKEN = ${JSON.stringify(token)};\nwindow.ROWCRAFT_POSTHOG_HOST = ${JSON.stringify(host)};\n`);
